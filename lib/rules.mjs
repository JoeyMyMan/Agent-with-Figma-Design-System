// Hand the workflow to whatever coding agents the project uses. One source (templates/agents-block.md + playbooks/),
// written where each agent already looks. AGENTS.md is always written; the rest are targets (config agents.targets):
//   agents-md  AGENTS.md                                   managed block between markers (read by most agents)
//   claude     CLAUDE.md                                   `@AGENTS.md` import, no copy of the rules
//   gemini     GEMINI.md                                   `@AGENTS.md` import, no copy of the rules
//   cursor     .cursor/rules/ds-workflow.mdc               the block, attached to style / component files
//   copilot    .github/instructions/ds-workflow.instructions.md   the block, `applyTo` style / component files
//   cline      .clinerules/ds-workflow.md (or the block inside a .clinerules file)
// "auto" = AGENTS.md + every target whose own file or folder already exists. Any other agent: agents.extraFiles
// (managed block in that file) and agents.skillsDirs (the playbooks as SKILL.md folders).
// Always: <playbooks.dir>/ — a copy of the playbooks and the Figma export script, versioned with the package.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describeSource, workKey } from './source.mjs';
import { writeText } from './util.mjs';

export const PKG = join(dirname(fileURLToPath(import.meta.url)), '..');
const PKG_JSON = JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8'));
export const VERSION = PKG_JSON.version;
const START = '<!-- ds-workflow:start (generated by `npx ds-workflow rules`; edit design-system.config.json or the package, not this block) -->';
const END = '<!-- ds-workflow:end -->';

/** known agents: how to detect them in a repo and what to write */
export const AGENT_TARGETS = {
  'agents-md': { detect: [] },
  claude: { detect: ['CLAUDE.md', '.claude'] },
  gemini: { detect: ['GEMINI.md', '.gemini'] },
  cursor: { detect: ['.cursor', '.cursorrules'] },
  copilot: { detect: ['.github/copilot-instructions.md', '.github/instructions'] },
  cline: { detect: ['.clinerules'] },
};

export function resolveTargets(cfg, root) {
  const t = cfg.agents?.targets ?? 'auto';
  if (t === 'auto') return ['agents-md', ...Object.entries(AGENT_TARGETS).filter(([, a]) => a.detect.some((f) => existsSync(join(root, f)))).map(([k]) => k)];
  const list = Array.isArray(t) ? t : String(t).split(',').map((s) => s.trim()).filter(Boolean);
  for (const k of list) if (!AGENT_TARGETS[k]) throw new Error(`unknown agent target "${k}" (known: ${Object.keys(AGENT_TARGETS).join(', ')}; use agents.extraFiles for others)`);
  return [...new Set(['agents-md', ...list])];
}

export function playbookList() {
  const dir = join(PKG, 'playbooks');
  return readdirSync(dir)
    .filter((d) => existsSync(join(dir, d, 'SKILL.md')))
    .sort()
    .map((d) => {
      const text = readFileSync(join(dir, d, 'SKILL.md'), 'utf8');
      const fm = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? '';
      const get = (k) => new RegExp(`^${k}:\\s*(.+)$`, 'm').exec(fm)?.[1]?.trim() ?? '';
      return { dir: d, name: get('name') || d, description: get('description') };
    });
}

export function agentsBlock(cfg) {
  const tpl = readFileSync(join(PKG, 'templates/agents-block.md'), 'utf8');
  const index = playbookList()
    .map((p) => `- \`${cfg.playbooks.dir}/${p.dir}/SKILL.md\` — ${p.description}`)
    .join('\n');
  const vars = {
    version: VERSION,
    name: cfg.designSystem.name,
    source: describeSource(cfg.designSystem.source, { withWorkFile: false }),
    workFile: workKey(cfg.designSystem.source) || '<not configured>',
    playbooksDir: cfg.playbooks.dir,
    prefix: cfg.tokens.prefix,
    css: cfg.tokens.css,
    proposed: cfg.tokens.proposed,
    componentDirs: cfg.check.componentDirs.map((d) => `\`${d}\``).join(', '),
    proposalPrefix: cfg.proposal.prefix,
    proposalPage: cfg.designSystem.proposalPage,
    screensPage: cfg.designSystem.screensPage,
    registryMd: cfg.registry.markdown,
    ledger: cfg.review.ledger,
    readyMarker: cfg.review.readyMarker,
    pendingMarker: cfg.review.pendingMarker,
    channel: cfg.review.channel,
    playbookIndex: index,
  };
  return tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => vars[k] ?? `{{${k}}}`).trim();
}

/** replace the managed block in a file's text, or append it */
export function upsertBlock(text, block) {
  const wrapped = `${START}\n${block}\n${END}`;
  const i = text.indexOf(START.slice(0, 24));
  const j = text.indexOf(END);
  if (i >= 0 && j > i) return text.slice(0, i) + wrapped + text.slice(j + END.length);
  return (text.trimEnd() ? `${text.trimEnd()}\n\n` : '') + wrapped + '\n';
}

/** add `@AGENTS.md` to an agent's own instruction file (created if missing) */
function importAgents(file, title) {
  const t = existsSync(file) ? readFileSync(file, 'utf8') : `# ${title}\n`;
  if (/^@AGENTS\.md\b/m.test(t)) return false;
  writeText(file, `${t.trimEnd()}\n\n@AGENTS.md\n`);
  return true;
}

export function writeRules(cfg, { root = cfg.root ?? '.', skillsDirs = [] } = {}) {
  const p = (f) => join(root, f);
  const done = [];
  const block = agentsBlock(cfg);
  const targets = resolveTargets(cfg, root);
  const exts = cfg.check.extensions.map((e) => e.replace(/^\./, ''));
  const globList = cfg.check.scan.flatMap((d) => exts.map((e) => `${d}/**/*.${e}`));
  const generated = '<!-- generated by `npx ds-workflow rules`; do not edit -->';

  const agents = p('AGENTS.md');
  writeText(agents, upsertBlock(existsSync(agents) ? readFileSync(agents, 'utf8') : '# AGENTS.md\n', block));
  done.push('AGENTS.md');

  if (targets.includes('claude') && importAgents(p('CLAUDE.md'), 'CLAUDE.md')) done.push('CLAUDE.md (+@AGENTS.md)');
  if (targets.includes('gemini') && importAgents(p('GEMINI.md'), 'GEMINI.md')) done.push('GEMINI.md (+@AGENTS.md)');
  if (targets.includes('cursor')) {
    const globs = cfg.check.scan.map((d) => `${d}/**/*.{${exts.join(',')}}`).join(',');
    writeText(
      p('.cursor/rules/ds-workflow.mdc'),
      `---\ndescription: Design-system rules (ds-workflow) — apply when writing pages, components or styles, or doing Figma tasks\nglobs: ${globs}\nalwaysApply: false\n---\n\n${generated}\n\n${block}\n`,
    );
    done.push('.cursor/rules/ds-workflow.mdc');
  }
  if (targets.includes('copilot')) {
    writeText(p('.github/instructions/ds-workflow.instructions.md'), `---\napplyTo: "${globList.join(',')}"\n---\n\n${generated}\n\n${block}\n`);
    done.push('.github/instructions/ds-workflow.instructions.md');
  }
  if (targets.includes('cline')) {
    const f = p('.clinerules');
    if (existsSync(f) && statSync(f).isFile()) {
      writeText(f, upsertBlock(readFileSync(f, 'utf8'), block));
      done.push('.clinerules (block)');
    } else {
      writeText(join(f, 'ds-workflow.md'), `${generated}\n\n${block}\n`);
      done.push('.clinerules/ds-workflow.md');
    }
  }
  for (const rel of cfg.agents?.extraFiles ?? []) {
    const f = p(rel);
    writeText(f, upsertBlock(existsSync(f) ? readFileSync(f, 'utf8') : '', block));
    done.push(`${rel} (block)`);
  }

  // playbooks copy (replaced wholesale: the package is the source)
  const dest = p(cfg.playbooks.dir);
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  cpSync(join(PKG, 'playbooks'), dest, { recursive: true });
  cpSync(join(PKG, 'figma'), join(dest, 'figma'), { recursive: true });
  writeText(join(dest, '.generated'), `Copied from ${PKG_JSON.name} ${VERSION} by \`npx ds-workflow rules\`. Do not edit here: change the package and re-run.\n`);
  done.push(`${cfg.playbooks.dir}/ (playbooks + figma/export-design-system.js)`);

  // the playbooks as skills, for every agent that loads SKILL.md folders
  for (const dir of [...new Set([...(cfg.agents?.skillsDirs ?? []), ...skillsDirs])]) {
    for (const pb of playbookList()) {
      const d = p(join(dir, pb.dir));
      rmSync(d, { recursive: true, force: true });
      cpSync(join(PKG, 'playbooks', pb.dir), d, { recursive: true });
    }
    done.push(`${dir}/ds-* (skills)`);
  }
  return done;
}
