// Upgrade report: what changed between two pinned versions (tokens and the component inventory). Written by `sync`
// into design-system/migrations/<old>→<new>.md; the migration PR works through it (playbooks/ds-upgrade).
import { walkTokens } from './util.mjs';

const flat = (tree) => {
  const out = new Map();
  for (const group of ['variables', 'paint', 'text', 'effect']) for (const [path, t] of walkTokens(tree?.[group] ?? {})) out.set(`${group}/${path.join('/')}`, JSON.stringify(t.$value) + (t.$extensions?.figma?.modes ? ` modes ${JSON.stringify(t.$extensions.figma.modes)}` : ''));
  return out;
};

export function diffTokens(oldTokens, newTokens) {
  const a = flat(oldTokens);
  const b = flat(newTokens);
  const added = [...b.keys()].filter((k) => !a.has(k));
  const removed = [...a.keys()].filter((k) => !b.has(k));
  const changed = [...b.keys()].filter((k) => a.has(k) && a.get(k) !== b.get(k)).map((k) => ({ name: k, from: a.get(k), to: b.get(k) }));
  // a removed and an added token with the same value in the same group: probably a rename
  const renamed = [];
  for (const r of [...removed]) {
    const g = r.split('/')[0];
    const match = added.find((n) => n.split('/')[0] === g && b.get(n) === a.get(r));
    if (match) {
      renamed.push({ from: r, to: match });
      removed.splice(removed.indexOf(r), 1);
      added.splice(added.indexOf(match), 1);
    }
  }
  return { added, removed, changed, renamed };
}

export function diffInventory(oldInv, newInv) {
  const a = new Map(oldInv.map((c) => [c.nodeId, c]));
  const b = new Map(newInv.map((c) => [c.nodeId, c]));
  const added = newInv.filter((c) => !a.has(c.nodeId));
  const removed = oldInv.filter((c) => !b.has(c.nodeId));
  const renamed = newInv.filter((c) => a.has(c.nodeId) && a.get(c.nodeId).name !== c.name).map((c) => ({ nodeId: c.nodeId, from: a.get(c.nodeId).name, to: c.name }));
  const props = newInv
    .filter((c) => a.has(c.nodeId) && JSON.stringify(a.get(c.nodeId).properties ?? null) !== JSON.stringify(c.properties ?? null))
    .map((c) => ({ nodeId: c.nodeId, name: c.name, from: a.get(c.nodeId).properties ?? null, to: c.properties ?? null }));
  return { added, removed, renamed, props };
}

export function diffReport({ from, to, oldTokens, newTokens, oldInv, newInv }) {
  const t = diffTokens(oldTokens, newTokens);
  const c = diffInventory(oldInv, newInv);
  const L = [`# Design-system upgrade ${from} → ${to}`, '', 'Generated by `ds-workflow sync`. Work through it with playbooks/ds-upgrade: mark renames and removals `deprecated` in the registry first and keep a transition period; confirm changed values with visual regression.', ''];
  const list = (title, items, fmt) => {
    L.push(`## ${title} (${items.length})`, '');
    if (!items.length) L.push('None', '');
    else L.push(...items.map((x) => `- ${fmt(x)}`), '');
  };
  list('Tokens removed — references in code will fail check', t.removed, (x) => `\`${x}\``);
  list('Tokens possibly renamed', t.renamed, (x) => `\`${x.from}\` → \`${x.to}\``);
  list('Token values changed', t.changed, (x) => `\`${x.name}\`: ${x.from} → ${x.to}`);
  list('Tokens added', t.added, (x) => `\`${x}\``);
  list('Components removed — registry entries that reference them will fail check', c.removed, (x) => `${x.name} (${x.nodeId})`);
  list('Components renamed', c.renamed, (x) => `${x.from} → ${x.to} (${x.nodeId})`);
  list('Component properties changed', c.props, (x) => `${x.name} (${x.nodeId}): ${JSON.stringify(x.from)} → ${JSON.stringify(x.to)}`);
  list('Components added', c.added, (x) => `${x.name} (${x.nodeId})`);
  L.push('## Migration notes', '', '(Written in the migration PR: which code and registry entries changed, visual-regression results.)', '');
  return L.join('\n');
}
