// design-system/components.registry.json → the readable table for the designer and review issues (generated markdown).
// One entry per code component:
//   { code, status, description, screens?, source?, figma?: {nodeId,name,url}, figmaProposal?: {nodeId,url},
//     figmaPending?: {nodeId,name,url}, variants?: {Prop: "values"}, note?, issue? }
import { join } from 'node:path';
import { paths, proposalCode } from './config.mjs';
import { readJson, writeText } from './util.mjs';

export const LABEL = { reuse: 'Reused', extend: 'Extended with variants (awaiting approval)', proposed: 'New components (awaiting approval)', approved: 'Approved', deprecated: 'Deprecated' };

export function render(cfg, reg) {
  const lock = reg.designSystem ?? '';
  const code = proposalCode(cfg);
  const out = [
    '# Component registry (generated)',
    '',
    `Generated by \`ds-workflow registry\` from \`${paths.registry}\`; do not edit. Design system ${cfg.designSystem.name} ${lock}. Process: ${cfg.playbooks.dir}/.`,
    '',
  ];
  const comps = reg.components ?? [];
  const counts = comps.reduce((a, c) => ((a[c.status] = (a[c.status] ?? 0) + 1), a), {});
  out.push(`${comps.length} entries: ${Object.entries(counts).map(([s, n]) => `${LABEL[s] ?? s} ${n}`).join(', ') || 'none'}.`, '');
  for (const status of Object.keys(LABEL)) {
    const list = comps.filter((c) => c.status === status);
    if (!list.length) continue;
    out.push(`## ${LABEL[status]} (${list.length})`, '', '| Code component | Purpose | Design-system component | Variants | Screens | Notes |', '| --- | --- | --- | --- | --- | --- |');
    for (const c of list) {
      const link = (f) => (f.url ? `[${f.name ?? f.nodeId}](${f.url})` : `${f.name ?? ''} ${f.nodeId}`);
      const fig = c.figma ? link(c.figma) : c.figmaPending ? `${link(c.figmaPending)} (not in the pinned version)` : status === 'proposed' ? `\`${cfg.proposal.prefix}/${c.code.replace(new RegExp(`^${code}/`), '')}\` (new)` : '—';
      const v = c.variants ? Object.entries(c.variants).map(([k, val]) => `**${k}**: ${val}`).join('<br>') : '';
      const prop = c.figmaProposal?.url ? ` · [proposal ↗](${c.figmaProposal.url})` : '';
      const src = c.source ? `<br>\`${c.source}\`` : '';
      const note = [c.note, c.issue].filter(Boolean).join(' ');
      out.push(`| \`${c.code}\`${src} | ${c.description ?? ''} | ${fig}${prop} | ${v} | ${(c.screens ?? []).join(' ')} | ${note.replace(/\|/g, '\\|')} |`);
    }
    out.push('');
  }
  return out.join('\n') + '\n';
}

export function renderProject(cfg, root = cfg.root ?? '.') {
  const reg = readJson(join(root, paths.registry), null);
  if (!reg) throw new Error(`${paths.registry} not found (ds-workflow init creates it)`);
  writeText(join(root, cfg.registry.markdown), render(cfg, reg));
  return { file: cfg.registry.markdown, count: reg.components?.length ?? 0 };
}
